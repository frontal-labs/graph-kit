// @graph-om/cli/src/commands/generate.ts
import fs from 'node:fs';
import path from 'node:path';
import { type ParsedNode, parseSchemaFile } from '@graph-om/sdk';
import { raiseGraphError } from '@graph-om/sdk/errors';

interface GenerateOptions {
  watch?: boolean;
}

export interface PropertyDef {
  name: string;
  type: string;
  primary?: boolean;
  unique?: boolean;
  nullable?: boolean;
  array?: boolean;
  default?: unknown;
}

export interface RelDef {
  name: string;
  type: string;
  direction: string;
  target: string;
  multiple: boolean;
}

export interface NodeDef {
  label: string;
  properties: PropertyDef[];
  relations: RelDef[];
}

export interface GenerateResult {
  nodes: NodeDef[];
  outputDir: string;
  files: string[];
}

const TS_TYPE_MAP: Record<string, string> = {
  string: 'string',
  number: 'number',
  boolean: 'boolean',
  date: 'Date',
  bigint: 'bigint',
  float: 'number',
  uuid: 'string',
  json: 'unknown',
};

const ZOD_TYPE_MAP: Record<string, string> = {
  string: 'z.string()',
  number: 'z.number()',
  boolean: 'z.boolean()',
  date: 'z.date()',
  bigint: 'z.bigint()',
  float: 'z.number()',
  uuid: 'z.string().uuid()',
  json: 'z.unknown()',
};

export function mapPropertyType(type: string, array?: boolean): string {
  const base = TS_TYPE_MAP[type] ?? 'unknown';
  return array ? `${base}[]` : base;
}

function convertParsedNode(parsed: ParsedNode): NodeDef {
  const properties: PropertyDef[] = Object.entries(parsed.properties).map(([name, config]) => ({
    name,
    type: config.type,
    primary: config.primary,
    unique: config.unique,
    nullable: config.nullable,
    array: config.array,
  }));

  const relations: RelDef[] = Object.entries(parsed.relations).map(([name, config]) => ({
    name,
    type: config.type,
    direction: config.direction,
    target: config.target,
    multiple: config.multiple ?? false,
  }));

  return { label: parsed.label, properties, relations };
}

export function loadSchema(schemaPath: string, exclude: string[] = []): NodeDef[] {
  const result = parseSchemaFile(schemaPath);

  if (result.errors.length > 0) {
    for (const error of result.errors) {
      console.warn(`⚠ ${error.file}:${error.line}:${error.column} - ${error.message}`);
    }
  }

  const nodes: NodeDef[] = [];
  for (const parsedNode of result.nodes) {
    if (exclude.includes(parsedNode.label)) continue;
    nodes.push(convertParsedNode(parsedNode));
  }

  return nodes;
}

export function generateNodeInterface(node: NodeDef): string {
  const props = node.properties.map((p) => {
    const type = mapPropertyType(p.type, p.array);
    return p.nullable ? `  ${p.name}?: ${type} | null;` : `  ${p.name}: ${type};`;
  });
  const relations = node.relations.map((r) =>
    r.multiple ? `  ${r.name}: ${r.target}Node[];` : `  ${r.name}?: ${r.target}Node | null;`,
  );
  return `export interface ${node.label}Node {\n${[...props, ...relations].join('\n')}\n}`;
}

export function generateWhereType(node: NodeDef): string {
  const props = node.properties.map((p) => {
    const type = mapPropertyType(p.type, p.array);
    return `  ${p.name}?: ${type} | WhereOperator<${type}>;`;
  });
  const combinators = [
    `  AND?: ${node.label}WhereInput[];`,
    `  OR?: ${node.label}WhereInput[];`,
    `  NOT?: ${node.label}WhereInput;`,
  ];
  return `export type ${node.label}WhereInput = {\n${[...props, ...combinators].join('\n')}\n};`;
}

export function generateCreateType(node: NodeDef): string {
  const props = node.properties
    .filter((p) => !p.primary || p.default !== undefined)
    .map((p) => {
      const type = mapPropertyType(p.type, p.array);
      const optional = p.default !== undefined || p.nullable ? '?' : '';
      return `  ${p.name}${optional}: ${type};`;
    })
    .join('\n');
  return `export type ${node.label}CreateInput = {\n${props}\n};`;
}

export function generateUpdateType(node: NodeDef): string {
  const props = node.properties
    .filter((p) => !p.primary)
    .map((p) => {
      const type = mapPropertyType(p.type, p.array);
      return `  ${p.name}?: ${type};`;
    })
    .join('\n');
  return `export type ${node.label}UpdateInput = {\n${props}\n};`;
}

function generateZodSchema(node: NodeDef): string {
  const props = node.properties
    .map((p) => {
      let zodType = ZOD_TYPE_MAP[p.type] ?? 'z.unknown()';
      if (p.array) zodType = `z.array(${zodType})`;
      if (p.nullable) zodType += '.nullable()';
      if (p.default !== undefined) zodType += `.default(${JSON.stringify(p.default)})`;
      return `  ${p.name}: ${zodType},`;
    })
    .join('\n');
  return `export const ${node.label}Schema = z.object({\n${props}\n});`;
}

export function generateTypesContent(nodes: NodeDef[]): string {
  return `// Auto-generated by Graph-OM CLI
// Type definitions for your graph schema
import type { WhereOperator } from '@graph-om/sdk';

${nodes.map((n) => generateNodeInterface(n)).join('\n\n')}

${nodes.map((n) => generateWhereType(n)).join('\n\n')}

${nodes.map((n) => generateCreateType(n)).join('\n\n')}

${nodes.map((n) => generateUpdateType(n)).join('\n\n')}
`.replace(/\n\n\n+/g, '\n\n');
}

export function generateZodContent(nodes: NodeDef[]): string {
  return `// Auto-generated by Graph-OM CLI
// Zod schemas for your graph schema
import { z } from 'zod';

${nodes.map((n) => generateZodSchema(n)).join('\n\n')}
`.replace(/\n\n\n+/g, '\n\n');
}

export function generateClientContent(nodes: NodeDef[]): string {
  const nodeMapFields = nodes.map((n) => `  '${n.label}': ${n.label}Node;`).join('\n');
  const imports = nodes.map((n) => `${n.label}Node`).join(', ');
  const nodeMapEntries = nodes
    .map((n) => {
      const props = n.properties
        .map(
          (p) =>
            `    ${p.name}: { type: '${p.type}'${p.primary ? ', primary: true' : ''}${p.unique ? ', unique: true' : ''}${p.nullable ? ', nullable: true' : ''}${p.array ? ', array: true' : ''} }`,
        )
        .join(',\n');
      return `  '${n.label}': {\n    label: '${n.label}',\n    properties: {\n${props}\n    },\n    relations: {},\n  }`;
    })
    .join(',\n');

  return `// Auto-generated by Graph-OM CLI
import { GraphClient, env } from '@graph-om/sdk';
import type { DriverAdapter, NodeConfig } from '@graph-om/sdk';
import { createNeo4jDriver } from '@graph-om/neo4j';
import type { ${imports} } from './types.js';

export type GraphNodeMap = {
${nodeMapFields}
};

export const nodeConfigs = {
${nodeMapEntries}
} as unknown as Record<string, NodeConfig<string, any>>;

export interface ClientConfig {
  uri?: string;
  username?: string;
  password?: string;
  database?: string;
}

export async function createClient(config: ClientConfig = {}): Promise<GraphClient> {
  const driver: DriverAdapter = createNeo4jDriver({
    type: 'neo4j',
    uri: config.uri || env.NEO4J_URI,
    username: config.username || env.NEO4J_USER,
    password: config.password || env.NEO4J_PASSWORD,
    database: config.database,
  });
  await driver.connect();
  const client = new GraphClient(driver, nodeConfigs);
  return client;
}
`;
}

export interface LoadedProjectConfig {
  schemaPath: string;
  outputDir: string;
  zod: boolean;
  exclude: string[];
}

export function loadProjectConfig(projectRoot: string): LoadedProjectConfig {
  let schemaPath = path.join(projectRoot, 'src', 'schema.ts');
  let outputDir = path.join(projectRoot, 'src', '__generated__');
  let zod = false;
  let exclude: string[] = [];

  const configPath = path.join(projectRoot, 'graph-om.config.ts');
  const configJsonPath = path.join(projectRoot, 'graph-om.config.json');

  if (fs.existsSync(configJsonPath)) {
    const raw = fs.readFileSync(configJsonPath, 'utf-8');
    try {
      const parsed = JSON.parse(raw) as {
        schema?: string;
        output?: { directory?: string; zod?: boolean };
        exclude?: string[];
      };
      if (parsed.schema) schemaPath = path.resolve(projectRoot, parsed.schema);
      if (parsed.output?.directory) outputDir = path.resolve(projectRoot, parsed.output.directory);
      if (parsed.output?.zod) zod = true;
      if (Array.isArray(parsed.exclude)) exclude = parsed.exclude;
    } catch {
      console.warn('⚠ Could not parse graph-om.config.json, using defaults.');
    }
  } else if (fs.existsSync(configPath)) {
    const raw = fs.readFileSync(configPath, 'utf-8');
    const schemaMatch = raw.match(/schema:\s*['"]([^'"]+)['"]/);
    const outputMatch = raw.match(/directory:\s*['"]([^'"]+)['"]/);
    const zodMatch = raw.match(/zod:\s*(true|false)/);
    const excludeMatch = raw.match(/exclude:\s*\[([^\]]*)\]/);
    if (schemaMatch?.[1]) {
      schemaPath = path.resolve(projectRoot, schemaMatch[1]);
    }
    if (outputMatch?.[1]) {
      outputDir = path.resolve(projectRoot, outputMatch[1]);
    }
    if (zodMatch?.[1] === 'true') zod = true;
    if (excludeMatch?.[1]) {
      exclude = [...excludeMatch[1].matchAll(/['"]([^'"]+)['"]/g)].map((m) => m[1] ?? '');
    }
  }

  return { schemaPath, outputDir, zod, exclude };
}

export function runGenerate(projectRoot: string): GenerateResult {
  const { schemaPath, outputDir, zod, exclude } = loadProjectConfig(projectRoot);

  if (!fs.existsSync(schemaPath)) {
    raiseGraphError(
      `Schema file not found at ${schemaPath}. ` +
        `Check the "schema" field in graph-om.config.ts or run \`graph-om init\`.`,
      { code: 'invalid_config', statusCode: 400, retry: { retryable: false } },
    );
  }

  fs.mkdirSync(outputDir, { recursive: true });

  const nodes = loadSchema(schemaPath, exclude);

  const files: string[] = [];

  fs.writeFileSync(path.join(outputDir, 'types.ts'), generateTypesContent(nodes));
  files.push('types.ts');

  fs.writeFileSync(path.join(outputDir, 'client.ts'), generateClientContent(nodes));
  files.push('client.ts');

  if (zod) {
    fs.writeFileSync(path.join(outputDir, 'zod.ts'), generateZodContent(nodes));
    files.push('zod.ts');
  }

  return { nodes, outputDir, files };
}

export async function generateCommand(options: GenerateOptions): Promise<void> {
  const projectRoot = process.cwd();

  try {
    const result = runGenerate(projectRoot);
    console.log(
      `✓ Generated types in ${path.relative(projectRoot, result.outputDir)}/ (${result.files.join(', ')})`,
    );
    console.log(`  Nodes: ${result.nodes.map((n) => n.label).join(', ') || '(none found)'}`);
  } catch (error) {
    console.error(`Error: ${(error as Error).message}`);
    process.exit(1);
  }

  if (options.watch) {
    const { schemaPath } = loadProjectConfig(projectRoot);
    const watchTargets = [schemaPath, path.join(projectRoot, 'metal.config.ts')].filter((p) =>
      fs.existsSync(p),
    );
    console.log('\n👀 Watching for changes... (Ctrl+C to stop)\n');

    let debounce: NodeJS.Timeout | undefined;
    const regenerate = (filename: string) => {
      if (debounce) clearTimeout(debounce);
      debounce = setTimeout(() => {
        try {
          console.log(`↻ ${filename} changed, regenerating...`);
          const result = runGenerate(projectRoot);
          console.log(`✓ Regenerated (${result.files.join(', ')})`);
        } catch (error) {
          console.error(`Error: ${(error as Error).message}`);
        }
      }, 150);
    };

    for (const target of watchTargets) {
      fs.watch(target, () => regenerate(path.basename(target)));
    }

    // Also watch the schema's directory for renames handled by re-running on any event
    await new Promise(() => {
      /* run forever */
    });
  }
}
